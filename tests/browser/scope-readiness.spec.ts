import {test,expect} from '@playwright/test';
import {fixture,testDb} from '../fixtures';
import {randomToken,sha256,sign} from '../../lib/security';
test.afterAll(()=>testDb.$disconnect());
test('เพิ่มฐานเป็นศูนย์แจ้งเหตุผล แล้วแก้ฝ่ายจากทะเบียนเพื่อเข้าฐานได้',async({page})=>{
  const f=await fixture(),token=randomToken();
  const person=await testDb.person.create({data:{code:'MISSING-DEPT',fullName:'บุคลากรรอกำหนดฝ่าย',hiredOn:f.year.startsOn}});
  await testDb.annualPersonnelScope.updateMany({where:{personId:f.persons[2].id},data:{included:false}});
  await testDb.authSession.create({data:{userId:f.admin.id,tokenHash:sha256(sign(token)),csrfToken:randomToken(),expiresAt:new Date(Date.now()+600000)}});
  await page.context().addCookies([{name:'management_session',value:token,url:'http://127.0.0.1:3001',httpOnly:true,sameSite:'Lax'}]);
  await page.goto('/admin');
  await page.locator(`#years form[action="/api/admin/years/${f.year.id}/scopes"]`).getByRole('button').click();
  const feedback=page.locator('.alert.success[role="status"]');
  await expect(feedback).toContainText('เพิ่มเข้าฐานได้ 0 คน');
  await expect(feedback).toContainText('ยังเพิ่มไม่ได้ 1 คน');
  await expect(feedback).toContainText('นำออกจากฐานไว้');
  const readiness=page.locator('#scope-readiness');
  await readiness.getByText('รายชื่อที่ต้องกำหนดฝ่าย (1 คน)',{exact:true}).click();
  await readiness.getByRole('link',{name:'MISSING-DEPT · บุคลากรรอกำหนดฝ่าย',exact:true}).click();
  const editor=page.locator('#person-'+person.id).locator('..');
  await editor.locator(':scope > summary').click();
  await editor.getByLabel('ฝ่ายปัจจุบัน / ฝ่ายที่จะย้าย').selectOption(f.departments[1].id);
  await editor.getByRole('button',{name:'บันทึกบุคลากร / ย้ายฝ่าย',exact:true}).click();
  await expect(feedback).toContainText('บันทึกข้อมูลแล้ว');
  await expect(page.locator('#scope-readiness')).toContainText('ยังไม่มีฝ่ายในปีนี้ 0 คน');
  expect(await testDb.annualPersonnelScope.count({where:{personId:person.id,included:true}})).toBe(1);
  expect(await testDb.trainingParticipation.count({where:{personId:person.id}})).toBe(0);
  expect((await testDb.annualPersonnelScope.findFirstOrThrow({where:{personId:f.persons[2].id}})).included).toBe(false);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
