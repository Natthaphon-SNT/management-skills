import {test,expect} from '@playwright/test';
import {fixture,testDb} from '../fixtures';
import {fiscalBounds,dateOnly} from '../../lib/calendar';
import {randomToken,sha256,sign} from '../../lib/security';
test.afterAll(()=>testDb.$disconnect());
test('Cron สร้าง ZIP ปีที่สิ้นสุด เก็บไม่ซ้ำ และให้แอดมินดาวน์โหลด/ลบเอง',async({page})=>{
  const f=await fixture(),bounds=fiscalBounds(f.year.year-1);
  const prior=await testDb.fiscalYear.create({data:{year:f.year.year-1,startsOn:dateOnly(bounds.start),endsOn:dateOnly(bounds.end),state:'closed',retention:{create:{}}}});
  const token=randomToken();await testDb.authSession.create({data:{userId:f.admin.id,tokenHash:sha256(sign(token)),csrfToken:randomToken(),expiresAt:new Date(Date.now()+600000)}});
  await page.context().addCookies([{name:'management_session',value:token,url:'http://127.0.0.1:3001',httpOnly:true,sameSite:'Lax'}]);
  expect((await page.request.get('/api/cron')).status()).toBe(401);
  const cron=()=>page.request.get('/api/cron',{headers:{Authorization:'Bearer e2e-local-cron-token-for-isolated-tests-only'}});
  const response=await cron();expect(response.status(),await response.text()).toBe(200);
  expect((await response.json()).annualReport.status).toBe('completed');
  const job=await testDb.exportJob.findFirstOrThrow({where:{kind:'annual_zip',fiscalYearId:prior.id}});
  expect((await cron()).status()).toBe(200);expect(await testDb.exportJob.count({where:{kind:'annual_zip'}})).toBe(1);
  await page.goto('/admin/retention?fiscalYearId='+prior.id);
  await expect(page.locator('#storage-monitor')).toContainText('80%');await expect(page.locator('#storage-monitor progress')).toBeVisible();
  const report=page.locator('#annual-reports > details').first();await report.locator(':scope > summary').click();
  await expect(report).toContainText('พร้อมดาวน์โหลด');
  const file=await page.request.get('/api/admin/annual-reports/'+job.id);expect(file.status()).toBe(200);expect((await file.body()).subarray(0,2).toString()).toBe('PK');
  await report.getByText('ลบ ZIP รายงานนี้เพื่อคืนพื้นที่',{exact:true}).click();
  await report.getByLabel('ที่เก็บ ZIP รายงานภายนอก').fill('Unit drive / reports.zip');await report.getByLabel('พิมพ์ DELETE เพื่อยืนยันลบ ZIP รายงาน').fill('DELETE');
  await report.getByRole('button',{name:'ยืนยันลบ ZIP รายงาน',exact:true}).click();
  await expect(page).toHaveURL(new RegExp('fiscalYearId='+prior.id));
  await expect(page.locator('#annual-reports')).toContainText('แอดมินนำไฟล์ออกแล้ว');
  expect((await testDb.exportJob.findUniqueOrThrow({where:{id:job.id}})).data).toBeNull();
  await cron();expect(await testDb.exportJob.count({where:{kind:'annual_zip'}})).toBe(1);
  const userToken=randomToken();await testDb.authSession.create({data:{userId:f.user.id,tokenHash:sha256(sign(userToken)),csrfToken:randomToken(),expiresAt:new Date(Date.now()+600000)}});
  await page.context().addCookies([{name:'management_session',value:userToken,url:'http://127.0.0.1:3001',httpOnly:true,sameSite:'Lax'}]);
  expect((await page.request.get('/api/admin/annual-reports/'+job.id)).status()).toBe(403);
  expect(await testDb.trainingParticipation.count()).toBe(2);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
